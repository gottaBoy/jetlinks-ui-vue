def parse(raw: str) -> np.ndarray:
    pts = []
    for line in raw.strip().split("\n"):
        a, b = line.split()
        pts.append((float(a), float(b)))
    return np.array(pts)


def main():
    w, h = 960, 768
    for label, raw in [("0.25m", RAW_025), ("0.5m", RAW_05)]:
        p = parse(raw)
        nx = p[:, 0] / w
        ny = p[:, 1] / h
        coef = np.polyfit(nx, ny, 4)
        pred = np.polyval(coef, nx)
        rmse = float(np.sqrt(np.mean((pred - ny) ** 2)))
        print(label, "rmse_norm_y", rmse)
        print("  coef high->low:", repr([float(c) for c in coef]))


if __name__ == "__main__":
    main()
